"""Live reverse auction: one buyer actor per supplier, independent shop transports and a shared quote board.

No prices are generated by the buyer model. It chooses a negotiating tactic; a shop returns the quote.
The offline transport is explicitly fictional; external mode never falls back to a fictional quote.
"""
from __future__ import annotations

import asyncio
import itertools
import json
import math
import uuid
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta, timezone

import httpx

from app.config import env
from .strategy import Allocation, Decision, NeedLine, Offer, SupplierProfile, supplier_terms, counter
from . import levers


def external_endpoints() -> dict[str, str]:
    raw = json.loads(env("MARKET_SUPPLIER_ENDPOINTS", "{}"))
    if not isinstance(raw, dict) or any(not isinstance(k, str) or not isinstance(v, str)
                                       or not v.startswith("https://") for k, v in raw.items()):
        raise ValueError("MARKET_SUPPLIER_ENDPOINTS must map supplier IDs to HTTPS URLs")
    return raw


def mode() -> str:
    value = env("MARKET_NEGOTIATION_MODE", "demo")
    if value not in ("demo", "external", "legacy"):
        raise ValueError("Unknown MARKET_NEGOTIATION_MODE")
    return value


@dataclass(frozen=True)
class Quote:
    offer: Offer
    arrives: date
    expires: datetime
    quote_id: str


@dataclass(frozen=True)
class Exchange:
    request: dict
    quote: Quote | None
    rival: Offer | None = None
    tactic: str | None = None


@dataclass
class Shop:
    """Independent offline shop; only this actor knows its private terms."""

    profile: SupplierProfile
    line: NeedLine
    today: date
    seed: str
    current: float | None = None

    async def ask(self, request: dict) -> Quote:
        await asyncio.sleep(0)  # independent actor, same async interface as HTTPS
        terms = supplier_terms(self.profile, self.line, self.seed)
        if self.current is None:
            self.current = terms.opening
        elif not self.profile.fixed_price:
            rival = request.get("competingUnitPrice")
            if request["tactic"] == "volume":
                target = self.current * 0.975
                self.current = round(max(terms.floor, min(self.current, target)), 2)
            else:
                self.current, _ = counter(terms, self.current, rival)
        # Small urgent orders retain the existing demo's full-capacity assumption.
        capacity = self.line.need if self.line.need <= 50 else terms.capacity
        offer = Offer(self.profile.id, self.line.product_id, self.current, capacity,
                      self.current <= terms.floor + 0.005, opening=terms.opening)
        return Quote(offer, self.today + timedelta(days=max(0, self.profile.lead_time_days)),
                     datetime.now(timezone.utc) + timedelta(minutes=5), uuid.uuid4().hex)


@dataclass
class HttpShop:
    profile: SupplierProfile
    line: NeedLine
    today: date
    endpoint: str
    client: httpx.AsyncClient

    async def ask(self, request: dict) -> Quote | None:
        response = await self.client.post(self.endpoint, json=request)
        response.raise_for_status()
        data = response.json()
        if data.get("status") == "unavailable":
            return None
        if data.get("status") != "quote" or data.get("productId") != self.line.product_id:
            raise ValueError("Invalid supplier quote")
        price, quantity = float(data["unitPrice"]), float(data["quantity"])
        if not math.isfinite(price) or not math.isfinite(quantity) or price <= 0 or quantity <= 0:
            raise ValueError("Invalid quote numbers")
        if abs(price * 100 - round(price * 100)) > 1e-6:
            raise ValueError("Quote must use EUR cents")
        if data.get("currency") != "EUR" or data.get("unit") != self.line.unit or data.get("deliveryIncluded") is not True:
            raise ValueError("Incompatible quote terms")
        if data.get("qualityMatches") is not True:
            raise ValueError("Product specification not confirmed")
        arrives = date.fromisoformat(data["arrives"])
        expires = datetime.fromisoformat(data["validUntil"])
        quote_id = data["quoteId"]
        if arrives < self.today or expires.tzinfo is None or expires <= datetime.now(timezone.utc) or not isinstance(quote_id, str) or not quote_id:
            raise ValueError("Expired or invalid quote")
        if not isinstance(data.get("final"), bool):
            raise ValueError("Missing final flag")
        return Quote(Offer(self.profile.id, self.line.product_id, price, min(quantity, self.line.need),
                           data["final"]), arrives, expires, quote_id)


async def choose_tactic(profile: SupplierProfile, options: tuple[str, ...], history: list[Exchange]) -> str:
    """The LLM can choose a tactic, not invent a quote or promise payment/commitment."""
    fallback = levers.MEMORY.choose(profile.id, options) or options[0]
    if len(options) == 1 or env("MARKET_AGENT_LLM", "1") == "0":
        return fallback
    from app.clients import LLMRequest, LLMText
    from app.schemas import ChatMessage
    from .voices import market_llm

    try:
        llm = market_llm()
        if llm.provider == "mock":
            return fallback
        data = [{"tactic": x.tactic, "price": x.quote.offer.price if x.quote else None} for x in history]
        request = LLMRequest(
            system="Choose the buyer's next negotiation tactic. Output only one allowed token. Never promise a contract, payment terms, or exclusivity.",
            messages=[ChatMessage(role="user", content=json.dumps({
                "allowed": options, "previousQuotes": data, "supplierProfile": profile.persona[:800],
            }))], max_tokens=16, thinking="disabled")
        async def read():
            return "".join([ev.delta async for ev in llm.stream(request) if isinstance(ev, LLMText)]).strip().lower()
        selected = await asyncio.wait_for(read(), 0.65)
        return selected if selected in options else fallback
    except Exception:
        return fallback


@dataclass
class BuyerAgent:
    profile: SupplierProfile
    line: NeedLine
    shop: Shop | HttpShop
    deadline: date
    session: str
    history: list[Exchange] = field(default_factory=list)
    quote: Quote | None = None
    failed: bool = False

    async def exchange(self, board: tuple[Quote, ...], round_no: int) -> None:
        previous = self.quote
        if round_no and (previous is None or previous.offer.final or self.failed):
            return
        rival = None
        tactic = "quote"
        if previous:
            comparable = [q.offer for q in board if q.offer.supplier_id != self.profile.id
                          and q.arrives <= self.deadline and q.offer.qty >= previous.offer.qty
                          and q.offer.price < previous.offer.price]
            rival = min(comparable, key=lambda o: (o.price, o.supplier_id), default=None)
            options = ("concurrence", "volume") if rival else ("volume", "geste")
            used = {x.tactic for x in self.history}
            unused = tuple(x for x in options if x not in used) or options
            tactic = await choose_tactic(self.profile, unused, self.history)
        request = {
            "sessionId": self.session, "round": round_no, "supplierId": self.profile.id,
            "productId": self.line.product_id, "product": self.line.name, "unit": self.line.unit,
            "quantity": self.line.need, "deliverBy": self.deadline.isoformat(), "tactic": tactic,
            "nonBinding": True,
        }
        if previous:
            request["previousQuoteId"] = previous.quote_id
        if rival and tactic == "concurrence":
            request["competingUnitPrice"] = rival.price  # never reveal competitor identity
        try:
            quote = await asyncio.wait_for(self.shop.ask(request), 1.2)
        except Exception:
            self.failed = True
            quote = None
        if quote and previous:
            # Latest response is authoritative, even if price or availability got worse.
            quote.offer.opening = previous.offer.opening or previous.offer.price
        elif quote:
            quote.offer.opening = quote.offer.price
        self.quote = quote
        self.history.append(Exchange(request, quote, rival if tactic == "concurrence" else None, tactic))


def optimize(line: NeedLine, quotes: list[Quote], profiles: dict[str, SupplierProfile], strict_min: bool) -> Decision:
    """Exact single-product allocation over active supplier sets: maximize coverage, then minimize cost.
    Within each set, first satisfy minimums, then fill cheapest capacity. Quantity is in whole or half units.
    """
    step = 0.5 if line.unit in ("kg", "liter") else 1.0
    needed = round(line.need / step)
    candidates = []
    for q in sorted(quotes, key=lambda q: q.offer.supplier_id):
        o = q.offer
        cap = min(needed, math.floor(o.qty / step + 1e-8))
        minimum = max(1, math.ceil(profiles[o.supplier_id].min_order / (o.price * step) - 1e-8)) if strict_min else 1
        if cap >= minimum:
            candidates.append((o, cap, minimum))
    best_key, best = (0, 0, 0, ()), []
    # ERP demo has ten suppliers; no exponential search for large external catalogues.
    if len(candidates) > 12:
        raise ValueError("Express market supports at most 12 responding suppliers")
    for n in range(1, len(candidates) + 1):
        for group in itertools.combinations(candidates, n):
            counts = {o.supplier_id: minimum for o, _, minimum in group}
            remaining = needed - sum(counts.values())
            if remaining < 0:
                continue
            for o, cap, minimum in sorted(group, key=lambda x: (x[0].price, -profiles[x[0].supplier_id].reliability, x[0].supplier_id)):
                take = min(remaining, cap - minimum)
                counts[o.supplier_id] += take
                remaining -= take
            allocs = [Allocation(o.supplier_id, o.product_id, counts[o.supplier_id] * step, o.price,
                                 o.opening if o.opening is not None else o.price) for o, _, _ in group]
            total = round(sum(a.qty * a.price for a in allocs), 2)
            key = (-(needed - remaining), total, len(group), tuple(a.supplier_id for a in allocs))
            if key < best_key:
                best_key, best = key, allocs
    covered = sum(a.qty for a in best)
    total = round(sum(a.qty * a.price for a in best), 2)
    reference = round(sum(a.qty * a.opening for a in best), 2)
    missing = round(line.need - covered, 3)
    return Decision(best, {line.product_id: missing} if missing > 0 else {}, [], total, reference,
                    round(reference - total, 2), line.need, covered)


async def run(line: NeedLine, profiles: dict[str, SupplierProfile], today: date, deadline: date,
              seed: str, *, external: bool = False, endpoints: dict[str, str] | None = None):
    """Concurrent quote/counter rounds. All actors see the same previous-round snapshot."""
    session = uuid.uuid4().hex
    async with httpx.AsyncClient(timeout=1.1, follow_redirects=False, trust_env=False) as client:
        agents = {}
        for sid, profile in sorted(profiles.items()):
            if external:
                if sid not in (endpoints or {}):
                    continue
                shop = HttpShop(profile, line, today, endpoints[sid], client)
            else:
                shop = Shop(profile, line, today, seed)
            agents[sid] = BuyerAgent(profile, line, shop, deadline, session)
        board = ()
        for round_no in range(3):
            await asyncio.gather(*(a.exchange(board, round_no) for a in agents.values()))
            board = tuple(a.quote for a in agents.values() if a.quote and a.quote.expires > datetime.now(timezone.utc))
            if not board or all(q.offer.final for q in board):
                break
        on_time = [q for q in board if q.arrives <= deadline]
        usable = on_time or list(board)
        decision = optimize(line, usable, profiles, strict_min=external)
        return agents, usable, decision
